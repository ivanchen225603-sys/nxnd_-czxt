# -*- coding: utf-8 -*-
"""把本项目的 `.xyz` 转成 CloudCompare / MeshLab 能打开的 PLY。

为什么需要它
------------
落盘的 `.xyz` 是**原厂二进制格式**（`[u32 count] + count x [f32 x,y,z, u16 ring]`），
CloudCompare 打不开。本工具转成 PLY，并顺带做三件在现场很要紧的事：

**1. 去掉双回波的重复点（默认开）**

2026-09-15 实测：每帧约 198 000 点里只有约 99 000 个是不同的测量 ——
**94% 的点成对出现，每一对的 ring 之差恰好是 128**。
而 `ring = block_index x 128 + 通道号`，所以一个报文里的两个 block
装的是同一次测量。原厂存档记录 `return_mode = 2`（双回波）：
实心表面的"最强回波"与"最后回波"落在同一个点上。

去重不丢任何信息，文件小一半，CloudCompare 里也不会被重影干扰。
要看原始双回波结构就加 `--keep-dup`。

▲ 连带影响：`CLAUDE.md` 里那条对照量「历史样本每帧在 ROI 内 5~6 万点」
  是**单回波**的量级。现场开着双回波时看到的是它的两倍（实测 ROI 内约 11 万），
  别据此误判"切帧不对"。

**2. 按高度上色（默认）**

原有的 `pointcloud.export_ply` 按 ring 上色，那是用来看"哪几线在起作用"的。
看货堆形状要按**离地高度**上色才有用。`--color ring` 可切回去。

**3. 额外写一个 height 标量场**

CloudCompare 会把 PLY 里多出来的 float 属性认成 scalar field，
可以在界面里自由改色标、做剖面、按高度过滤。

用法
----
    python3 cli/export_ply.py 某帧.xyz                      # 单帧
    python3 cli/export_ply.py a_1of3.xyz a_2of3.xyz a_3of3.xyz -o 合并.ply
    python3 cli/export_ply.py 某帧.xyz --crop box           # 只导车厢
    python3 cli/export_ply.py 某帧.xyz --crop roi           # 只导 ROI 内
    python3 cli/export_ply.py 某帧.xyz --ascii              # ASCII PLY（体积大，但可读）
"""
from __future__ import annotations

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from cli import _common                          # noqa: E402
from app.pointcloud import load_xyz              # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__))))
from roi_audit import find_boxes, main_box       # noqa: E402

GROUND_Z = -5.23
ROI_X, ROI_Y, ROI_Z = (-2.0, 2.0), (-11.0, 8.0), (-6.0, -0.75)


def dedup(xyz, ring, decimals=4):
    """去掉双回波造成的重复点，返回 (xyz, ring, 去掉了多少)。

    按坐标四舍五入到 `decimals` 位去重（0.1 mm）——雷达的距离量化远粗于此，
    所以同一次测量的两个回波坐标是逐位相同的，不会误伤真正相邻的两个点。
    保留 ring 较小的那一个（block 0）。
    """
    if len(xyz) == 0:
        return xyz, ring, 0
    key = np.round(xyz, decimals)
    order = np.lexsort((ring, key[:, 2], key[:, 1], key[:, 0]))
    k = key[order]
    keep = np.ones(len(k), bool)
    keep[1:] = (np.diff(k, axis=0) != 0).any(axis=1)
    idx = order[keep]
    idx.sort()
    return xyz[idx], ring[idx], len(xyz) - len(idx)


def colorize(h, mode, ring):
    """给每个点上色。h 是离地高度。"""
    n = len(h)
    if mode == "none":
        return np.tile(np.array([[200, 200, 200]], np.uint8), (n, 1))
    if mode == "ring":
        r = ring.astype(np.float64)
        span = max(float(r.max() - r.min()), 1.0)
        t = (r - r.min()) / span
    else:                                   # height
        lo, hi = np.percentile(h, [2, 98])
        span = max(hi - lo, 1e-6)
        t = np.clip((h - lo) / span, 0.0, 1.0)
    # 蓝 -> 青 -> 绿 -> 黄 -> 红，比单调渐变更容易看出货堆的起伏
    r = np.clip(1.5 - np.abs(4 * t - 3), 0, 1)
    g = np.clip(1.5 - np.abs(4 * t - 2), 0, 1)
    b = np.clip(1.5 - np.abs(4 * t - 1), 0, 1)
    return (np.stack([r, g, b], axis=1) * 255).astype(np.uint8)


def write_ply(path, xyz, rgb, height, ascii_mode=False, ground_z=GROUND_Z):
    """写 PLY。height 作为额外的 float 属性 —— CloudCompare 会认成 scalar field。"""
    n = len(xyz)
    head = ["ply",
            "format ascii 1.0" if ascii_mode else "format binary_little_endian 1.0",
            # PLY 头必须是 ASCII，注释里不能写中文
            "comment generated by cli/export_ply.py",
            "comment ground_z=%.3f height=z-ground_z (scalar field)" % ground_z,
            "element vertex %d" % n,
            "property float x", "property float y", "property float z",
            "property uchar red", "property uchar green", "property uchar blue",
            "property float height",
            "end_header"]
    if ascii_mode:
        with open(path, "w", encoding="ascii", newline="\n") as f:
            f.write("\n".join(head) + "\n")
            if n:
                np.savetxt(f, np.column_stack([xyz, rgb, height]),
                           fmt="%.4f %.4f %.4f %d %d %d %.4f")
        return
    rec = np.zeros(n, dtype=[("x", "<f4"), ("y", "<f4"), ("z", "<f4"),
                             ("red", "u1"), ("green", "u1"), ("blue", "u1"),
                             ("height", "<f4")])
    rec["x"], rec["y"], rec["z"] = xyz[:, 0], xyz[:, 1], xyz[:, 2]
    rec["red"], rec["green"], rec["blue"] = rgb[:, 0], rgb[:, 1], rgb[:, 2]
    rec["height"] = height
    with open(path, "wb") as f:
        f.write(("\n".join(head) + "\n").encode("ascii"))
        f.write(rec.tobytes())


def main(argv=None):
    _common.setup_console()
    ap = argparse.ArgumentParser(description="把 .xyz 转成 CloudCompare 能开的 PLY")
    ap.add_argument("inputs", nargs="+", help="一个或多个 .xyz（多个会合并）")
    ap.add_argument("-o", "--out", default="", help="输出 .ply（默认同名改后缀）")
    ap.add_argument("--crop", choices=["none", "roi", "box"], default="none",
                    help="none=整帧（默认）/ roi=只要 ROI 内 / box=只要车厢")
    ap.add_argument("--color", choices=["height", "ring", "none"], default="height")
    ap.add_argument("--ground-z", type=float, default=GROUND_Z)
    ap.add_argument("--keep-dup", action="store_true",
                    help="保留双回波的重复点（默认去重）")
    ap.add_argument("--ascii", action="store_true", help="写 ASCII PLY（约大 4 倍）")
    args = ap.parse_args(argv)
    _common.ensure_root()

    G = args.ground_z
    xs, rs = [], []
    for p in args.inputs:
        fr = load_xyz(p)
        xs.append(np.asarray(fr.xyz, np.float64))
        r = fr.ring
        rs.append(np.zeros(len(xs[-1]), np.int32) if r is None
                  else np.asarray(r, np.int32))
        print("读入 %-52s %8d 点" % (os.path.basename(p), len(xs[-1])))
    xyz = np.vstack(xs)
    ring = np.concatenate(rs)
    n0 = len(xyz)

    if not args.keep_dup:
        xyz, ring, dropped = dedup(xyz, ring)
        print("去重   : -%d 点（双回波，ring 差 128 的成对点）-> %d"
              % (dropped, len(xyz)))
        if dropped and len(args.inputs) == 1 and dropped > n0 * 0.3:
            print("         这是 return_mode=2（双回波）的正常现象，不是丢包或 bug")

    if args.crop == "roi":
        m = ((xyz[:, 0] >= ROI_X[0]) & (xyz[:, 0] <= ROI_X[1]) &
             (xyz[:, 1] >= ROI_Y[0]) & (xyz[:, 1] <= ROI_Y[1]) &
             (xyz[:, 2] >= ROI_Z[0]) & (xyz[:, 2] <= ROI_Z[1]))
        xyz, ring = xyz[m], ring[m]
        print("裁 ROI : -> %d 点" % len(xyz))
    elif args.crop == "box":
        bs = find_boxes(xyz, G)
        mi = main_box(bs)
        if mi is None:
            print("没找到车厢，改为不裁剪")
        else:
            b = bs[mi]
            m = ((xyz[:, 0] >= b["x0"]) & (xyz[:, 0] <= b["x1"]) &
                 (xyz[:, 1] >= b["y0"]) & (xyz[:, 1] <= b["y1"]) &
                 (xyz[:, 2] - G > 0.3) & (xyz[:, 2] - G < 5.0))
            xyz, ring = xyz[m], ring[m]
            print("裁车厢 : x %.2f..%.2f  y %.2f..%.2f -> %d 点"
                  % (b["x0"], b["x1"], b["y0"], b["y1"], len(xyz)))

    if len(xyz) == 0:
        print("裁完一个点都不剩，没有输出。")
        return 2

    h = (xyz[:, 2] - G).astype(np.float32)
    rgb = colorize(h, args.color, ring)
    out = args.out or (os.path.splitext(args.inputs[0])[0] + ".ply")
    write_ply(out, xyz, rgb, h, ascii_mode=args.ascii, ground_z=G)
    mb = os.path.getsize(out) / 1e6
    print("-" * 66)
    print("已写出 %s" % out)
    print("  %d 点  %.1f MB  %s  上色=%s"
          % (len(xyz), mb, "ASCII" if args.ascii else "二进制", args.color))
    print("  离地高度 %.2f .. %.2f m（已作为 height 标量场写入，"
          "CloudCompare 里可按它改色标/做剖面）" % (h.min(), h.max()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
