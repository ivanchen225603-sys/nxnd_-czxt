#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
pc_tool.py — 车辆点云数据工具
================================================================
用途：脱离原始 EXE/DLL，独立读取与解析本系统的数据文件。
      用于验证逆向结论、二次开发、数据迁移。

子命令
------
  info   <file.xyz> ...        打印点云头信息与几何统计（对照 reason.txt）
  csv    <file.xyz> <out.csv>  转成文本 CSV(x,y,z,ring)
  pcd    <file.xyz> <out.pcd>  转成 PCL 的 .pcd（ascii）
  batch  <dir>                 批量统计 baseline 下全部样本
  udp    <packet.bin>          解析一帧 1100 字节 UDP 报文
  gen                     生成一帧模拟 UDP 报文，便于抓包前自测

数据格式（逆向结论，100% 匹配 10/10 个实测样本）
------------------------------------------------
  .xyz = [uint32 count] + count × [float32 x, float32 y, float32 z, uint16 ring]
         头 4 字节 + 每点 14 字节。

  UDP  = 1100 字节（见 config/config.json 的 packet 段）
         offset   0..11   包头/时间戳/序号
         offset  12       angle1  (uint16, ×angle_scale(0.01) 度)
         offset  14       block1  128 通道 × 4 字节 = 512
         offset 526       angle2  (uint16)
         offset 528       block2  128 通道 × 4 字节 = 512
         offset 1042      保留 12 字节
         offset 1054      IMU 46 字节（+30 为 acc_x）
"""

import sys, os, struct, math, csv, zlib, argparse

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from app.sample_paths import discover_samples
from app.settings import baseline_rel

# Windows 控制台默认不是 UTF-8，中文与 √/× 会直接抛 UnicodeEncodeError 把脚本打断。
# cli/ 下由 _common.setup_console() 统一处理，tools/ 不依赖 _common，所以自己拉齐。
for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")   # py3.7+
    except Exception:                                        # noqa: BLE001
        pass

XYZ_DTYPE = "<3fH"          # x,y,z,ring
XYZ_REC   = struct.calcsize(XYZ_DTYPE)   # = 14
assert XYZ_REC == 14


# ----------------------------------------------------------------------------
#  点云读写
# ----------------------------------------------------------------------------
def read_xyz(path):
    """返回 (count, [(x,y,z,ring), ...])"""
    with open(path, "rb") as f:
        raw = f.read()
    if len(raw) < 4:
        raise ValueError("文件过短，不是合法的 .xyz")
    n = struct.unpack_from("<I", raw, 0)[0]
    if len(raw) != 4 + n * XYZ_REC:
        # 容错：以实际长度为准
        n = (len(raw) - 4) // XYZ_REC
    out = []
    off = 4
    for _ in range(n):
        out.append(struct.unpack_from(XYZ_DTYPE, raw, off))
        off += XYZ_REC
    return n, out


def write_pcd(pts, path, comment="generated by pc_tool.py"):
    with open(path, "w", encoding="ascii") as f:
        f.write("# .PCD v0.7 - Point Cloud Data file format\n")
        f.write("VERSION 0.7\nFIELDS x y z intensity\n")
        f.write("SIZE 4 4 4 4\nTYPE F F F F\nCOUNT 1 1 1 1\n")
        f.write("WIDTH %d\nHEIGHT 1\nVIEWPOINT 0 0 0 1 0 0 0\n" % len(pts))
        f.write("POINTS %d\nDATA ascii\n" % len(pts))
        for x, y, z, r in pts:
            f.write("%.4f %.4f %.4f %d\n" % (x, y, z, r))


def stats(pts):
    if not pts:
        return {}
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]; zs = [p[2] for p in pts]
    rings = sorted(set(p[3] for p in pts))
    def pct(a, q):
        a = sorted(a); i = min(len(a) - 1, max(0, int(len(a) * q)))
        return a[i]
    return dict(n=len(pts),
                x=(min(xs), max(xs)), y=(min(ys), max(ys)), z=(min(zs), max(zs)),
                z_p30=pct(zs, 0.30), z_p50=pct(zs, 0.50), z_p90=pct(zs, 0.90),
                ring_min=rings[0], ring_max=rings[-1])


# ----------------------------------------------------------------------------
#  UDP 报文解析
# ----------------------------------------------------------------------------
def parse_udp(buf, cfg=None):
    cfg = cfg or {}
    p         = cfg.get("packet", {})
    proc      = cfg.get("processing", {})
    N         = p.get("channels", 128)
    a1_off    = p.get("angle1_offset", 12)
    a2_off    = p.get("angle2_offset", 526)
    b1_off    = p.get("block1_data_offset", 14)
    b2_off    = p.get("block2_data_offset", 528)
    imu_off   = p.get("imu_offset", 1054)
    a_scale   = proc.get("angle_scale", 0.01)
    d_scale   = proc.get("distance_scale", 4.0)
    off_r     = proc.get("offset_r", 15.640617)
    deg2rad   = proc.get("deg_to_rad", math.pi / 180.0)
    yaw       = proc.get("yaw_offset_deg", -93.0)
    dmin      = proc.get("min_distance_mm", 100.0)
    chan_size = p.get("point_size", 4)

    out = {"size": len(buf), "blocks": []}
    for bi, (ao, bo) in enumerate(((a1_off, b1_off), (a2_off, b2_off))):
        ang_raw = struct.unpack_from("<H", buf, ao)[0]
        ang_deg = ang_raw * a_scale
        pts = []
        for ch in range(N):
            o = bo + ch * chan_size
            if o + chan_size > len(buf):
                break
            dist_raw = struct.unpack_from("<H", buf, o)[0]
            r = dist_raw * d_scale - off_r          # 毫米/单位按原始标定
            if r < dmin or r <= 0:
                continue
            pts.append((ang_deg, ch, r))
        out["blocks"].append({"angle_deg": ang_deg, "angle_raw": ang_raw,
                              "points": len(pts), "sample": pts[:3]})
    if imu_off + 6 <= len(buf):
        out["imu_acc"] = struct.unpack_from("<3h", buf, imu_off + 30) \
            if imu_off + 36 <= len(buf) else None
    out["yaw_offset_deg"] = yaw
    out["deg_to_rad"] = deg2rad
    return out


def gen_packet(path, cfg=None):
    cfg = (cfg or {}).get("packet", {})
    N = cfg.get("channels", 128); size = cfg.get("packet", 1100)
    size = cfg.get("size", 1100)
    buf = bytearray(size)
    struct.pack_into("<I", buf, 0, 0x00000001)
    struct.pack_into("<H", buf, cfg.get("angle1_offset", 12), 1234)
    struct.pack_into("<H", buf, cfg.get("angle2_offset", 526), 1266)
    for ch in range(N):
        struct.pack_into("<H", buf, cfg.get("block1_data_offset", 14) + ch * 4,
                         100 + ch * 3)
        struct.pack_into("<H", buf, cfg.get("block2_data_offset", 528) + ch * 4,
                         100 + ch * 3)
    open(path, "wb").write(bytes(buf))
    return path


# ----------------------------------------------------------------------------
#  CLI
# ----------------------------------------------------------------------------
def cmd_info(a):
    for f in a.files:
        n, pts = read_xyz(f)
        s = stats(pts)
        rp = f + ".reason.txt"
        reason = ""
        if os.path.exists(rp):
            reason = open(rp, encoding="utf-8").read().strip()
        print("=" * 74)
        print(f"文件 : {f}")
        print(f"点数 : {n}")
        if s:
            print(f"X    : {s['x'][0]:9.3f} ~ {s['x'][1]:9.3f}")
            print(f"Y    : {s['y'][0]:9.3f} ~ {s['y'][1]:9.3f}")
            print(f"Z    : {s['z'][0]:9.3f} ~ {s['z'][1]:9.3f}"
                  f"   p30={s['z_p30']:.3f}  p50={s['z_p50']:.3f}  p90={s['z_p90']:.3f}")
            print(f"ring : {s['ring_min']} ~ {s['ring_max']}")
        if reason:
            print(f"判定 : {reason}")


def cmd_csv(a):
    n, pts = read_xyz(a.src)
    with open(a.dst, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["x", "y", "z", "ring"])
        w.writerows(pts)
    print(f"已写出 {n} 点 -> {a.dst}")


def cmd_pcd(a):
    n, pts = read_xyz(a.src)
    write_pcd(pts, a.dst)
    print(f"已写出 {n} 点 -> {a.dst}")


def cmd_batch(a):
    found = discover_samples(a.dir, role="detection")
    found.report()
    files = [sample.path for sample in found.samples]
    print(f"{'样本':<24}{'点数':>7}{'zmin':>9}{'z_p30':>9}{'内点比':>8}  判定")
    for f in files:
        n, pts = read_xyz(f)
        s = stats(pts)
        if not s:
            print(f"{f}: 空点云，未计算统计")
            continue
        rp = f + ".reason.txt"
        reason = open(rp, encoding="utf-8").read().strip() if os.path.exists(rp) else ""
        # 复现 config.detect_empty.floor.z_percentile = 30 的内点占比
        thr = s["z_p30"] + 0.015
        ratio = sum(1 for p in pts if p[2] < thr) / max(1, n)
        tag = os.path.basename(os.path.dirname(f))
        print(f"{tag + '/' + os.path.basename(f)[:9]:<24}{n:>7}{s['z'][0]:>9.3f}"
              f"{s['z_p30']:>9.3f}{ratio * 100:>7.1f}%  {reason}")
    print(f"\n共 {len(files)} 个样本")


def cmd_udp(a):
    buf = open(a.file, "rb").read()
    import json
    cfg = {}
    for c in ("config/config.json", os.path.join(os.path.dirname(a.file), "config.json")):
        if os.path.exists(c):
            cfg = json.load(open(c, encoding="utf-8")); break
    r = parse_udp(buf, cfg)
    print(f"报文长度 : {r['size']} 字节")
    for i, b in enumerate(r["blocks"], 1):
        print(f"  block{i}: angle={b['angle_deg']:.2f}° 有效点={b['points']}  "
              f"样例={b['sample']}")
    print(f"  imu_acc  : {r.get('imu_acc')}")
    print(f"  yaw_offset={r['yaw_offset_deg']}°  deg2rad={r['deg_to_rad']:.6f}")


def cmd_gen(a):
    print("已生成模拟报文 ->", gen_packet(a.out))


def main():
    ap = argparse.ArgumentParser(description="车辆点云数据工具")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("info"); p.add_argument("files", nargs="+"); p.set_defaults(f=cmd_info)
    p = sub.add_parser("csv"); p.add_argument("src"); p.add_argument("dst"); p.set_defaults(f=cmd_csv)
    p = sub.add_parser("pcd"); p.add_argument("src"); p.add_argument("dst"); p.set_defaults(f=cmd_pcd)
    p = sub.add_parser("batch"); p.add_argument("dir", nargs="?", default=baseline_rel()); p.set_defaults(f=cmd_batch)
    p = sub.add_parser("udp"); p.add_argument("file"); p.set_defaults(f=cmd_udp)
    p = sub.add_parser("gen"); p.add_argument("out", nargs="?", default="sample_packet.bin"); p.set_defaults(f=cmd_gen)

    a = ap.parse_args()
    a.f(a)


if __name__ == "__main__":
    main()
