-- CarPointCloud DM8 v7 -> v8: correlated third-party interaction audit.
-- The existing ApiAccessLog rows remain valid; new columns are nullable for backward compatibility.
-- Each HTTP hop in one business interaction shares InteractionId.

SET SCHEMA CarPointCloud;

BEGIN
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'INTERACTIONID') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD InteractionId VARCHAR(64) NULL';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'INTEGRATIONTYPE') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD IntegrationType VARCHAR(32) NULL';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'DIRECTION') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD Direction VARCHAR(16) NULL';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'CALLERSYSTEM') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD CallerSystem VARCHAR(64) NULL';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'TARGETSYSTEM') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD TargetSystem VARCHAR(64) NULL';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'WORKFLOWID') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD WorkflowId VARCHAR(128) NULL';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'EVENTID') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD EventId VARCHAR(128) NULL';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'LICENSEPLATE') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD LicensePlate VARCHAR(32) NULL';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'CAMERAIDENTIFIER') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD CameraIdentifier VARCHAR(64) NULL';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'ATTEMPTNO') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD AttemptNo INT NULL';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'APIACCESSLOG' AND COLUMN_NAME = 'RESPONSEHEADERSJSON') THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ApiAccessLog ADD ResponseHeadersJson TEXT NULL';
  END IF;
END;
