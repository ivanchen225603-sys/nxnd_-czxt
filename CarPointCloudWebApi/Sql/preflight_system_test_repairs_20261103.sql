FROM USER_TAB_COLUMNS
WHERE (TABLE_NAME='LICENSEPLATERECORD' AND COLUMN_NAME='ENTERID')
   OR (TABLE_NAME='COALVOLUMERECORD' AND COLUMN_NAME IN ('MEASUREMENTSTARTEDAT','MEASUREMENTENDEDAT'))
   OR (TABLE_NAME='VEHICLEDIMENSIONRECORD' AND COLUMN_NAME IN ('ACTUALRIBCOUNT','MAXIMUMWIDTHCM'))
   OR (TABLE_NAME='VEHICLEDIMENSIONHIGHLOWPLATE' AND COLUMN_NAME='LENGTHCM')
   OR (TABLE_NAME='PLATEACQUISITIONJOB' AND COLUMN_NAME='CANDIDATEJSON')
ORDER BY TABLE_NAME, COLUMN_NAME;
